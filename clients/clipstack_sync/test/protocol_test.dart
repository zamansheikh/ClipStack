import 'dart:async';
import 'dart:io';
import 'dart:math';
import 'dart:typed_data';

import 'package:async/async.dart';
import 'package:clipstack_sync/clipstack_sync.dart';
import 'package:clipstack_sync/src/crypto.dart';
import 'package:clipstack_sync/src/protocol.dart';
import 'package:test/test.dart';

/// In-memory responder policy with an optional open pairing window.
class _Policy implements ResponderPolicy {
  final paired = <String, Uint8List>{};
  Uint8List? token;

  @override
  Uint8List? pairedKey(String deviceId) => paired[deviceId];

  @override
  bool get pairingOpen => token != null;

  @override
  bool consumePairingToken(Uint8List candidate) {
    final ok = token != null && _same(token!, candidate);
    if (ok) token = null; // single use
    return ok;
  }

  @override
  void onPaired(DeviceInfo device, Uint8List staticKey) => paired[device.id] = staticKey;
}

bool _same(List<int> a, List<int> b) => a.length == b.length && List.generate(a.length, (i) => a[i] == b[i]).every((x) => x);

Uint8List _randomBytes(int n) => Uint8List.fromList(List.generate(n, (_) => Random.secure().nextInt(256)));

void main() {
  group('wire format', () {
    test('pairing link round trip', () {
      final link = PairingLink(
        device: const DeviceInfo(id: '0b6f1f3c-6c3e-4f7e-9d7a-2a1d6c9e8f10', name: "Zaman's MacBook Pro", platform: 'macos'),
        publicKey: _randomBytes(32),
        token: _randomBytes(16),
        port: 47474,
        hosts: ['192.168.68.53', '10.0.0.4'],
      );
      final parsed = PairingLink.parse(link.toUri());
      expect(parsed.device.name, "Zaman's MacBook Pro");
      expect(parsed.publicKey, link.publicKey);
      expect(parsed.token, link.token);
      expect(parsed.hosts, link.hosts);
      expect(parsed.port, 47474);
    });

    test('message with body round trip', () {
      final clip = ClipMessage.png(_randomBytes(5000), origin: newDeviceId());
      final decoded = ClipMessage.fromMessage(Message.decode(clip.toMessage().encode()));
      expect(decoded.kind, 'image');
      expect(decoded.body, clip.body);
      expect(decoded.mime, 'image/png');
    });

    test('text that is a web address becomes a url clip', () {
      expect(ClipMessage.text('https://example.com/a?b=1', origin: newDeviceId()).kind, 'url');
      expect(ClipMessage.text('see https://example.com', origin: newDeviceId()).kind, 'text');
    });

    test('frame decoder reassembles split and merged chunks', () async {
      final a = encodeFrame([1, 2, 3]), b = encodeFrame(List.filled(300, 7));
      final all = Uint8List.fromList([...a, ...b]);
      final chunks = [all.sublist(0, 2), all.sublist(2, 9), all.sublist(9)];
      final frames = await Stream.fromIterable(chunks).transform(const FrameDecoder()).toList();
      expect(frames.map((f) => f.length), [3, 300]);
    });
  });

  group('interop with the Mac (Swift/CryptoKit) implementation', () {
    // Vector generated by ClipStack/Sync on the Mac: private key byte i = (i + base) mod 256.
    Uint8List key(int base) => Uint8List.fromList(List.generate(32, (i) => (i + base) % 256));
    Uint8List hex(String s) => Uint8List.fromList([for (var i = 0; i < s.length; i += 2) int.parse(s.substring(i, i + 2), radix: 16)]);
    String toHex(List<int> b) => b.map((x) => x.toRadixString(16).padLeft(2, '0')).join();

    test('frames, session keys and first encrypted frame match byte for byte', () async {
      final sI = await DeviceIdentity.restore(
          const DeviceInfo(id: '00000000-0000-4000-8000-000000000001', name: 'I', platform: 'android'), key(0x10));
      final sR = await DeviceIdentity.restore(
          const DeviceInfo(id: '00000000-0000-4000-8000-000000000002', name: 'R', platform: 'macos'), key(0x50));
      final eI = (await DeviceIdentity.restore(sI.device, key(0x30))).keyPair;
      final eR = (await DeviceIdentity.restore(sR.device, key(0x70))).keyPair;
      expect(toHex(sI.publicKey), 'd89e3bad79437dbed9f843418304f460ff05c7fe81fe4a9577a804cb9367ff66');
      expect(toHex(sR.publicKey), '392d174a38b3b1beafaf1fe824870841c5fa531bc6eafdb6402c124664488c1c');

      final f1 = buildFrame1(ephemeralPublic: await publicKeyOf(eI), staticPublic: sI.publicKey, deviceId: sI.device.id);
      final f2 = buildFrame2(await publicKeyOf(eR));
      expect(toHex(f1),
          '4353763134e42d4af5ef94a07a3a84201b889d4cd1a743cb27b11b6a10438a8feb8e5847d89e3bad79437dbed9f843418304f460ff05c7fe81fe4a9577a804cb9367ff6630303030303030302d303030302d343030302d383030302d303030303030303030303031');
      expect(toHex(f2), '4353763123b7bb8c91ae008711fb12846780bcdf1e065f821bdfec49f57e7c7dcd4c4823');

      final keys = await deriveInitiatorKeys(
          ephemeral: eI, static: sI.keyPair, responderStatic: sR.publicKey, responderEphemeral: await publicKeyOf(eR), frame1: f1, frame2: f2);
      expect(toHex(await keys.send.extractBytes()), '66a8b10240f77877a7e40cfac58615f03c27a397a57f11b6cb1c1c771ce83cbb');
      expect(toHex(await keys.receive.extractBytes()), '6561c378d5b614115f65bd1a8dcdafff9269ecca6f55b242b016e43e88dc1bc0');

      final ping = Message({'t': 'ping'}).encode();
      expect(toHex(ping), '0000000c7b2274223a2270696e67227d');
      expect(toHex(await FrameCipher(keys.send).seal(ping)), '38814ad546205264d6b08f436b2e09ebc603556936ef6fab6238797e7e5c269c');
      expect(hex('00'), [0]);
    });
  });

  group('handshake keys', () {
    test('both sides derive mirrored keys; a wrong static key does not', () async {
      final initiator = await DeviceIdentity.generate(name: 'phone', platform: 'android');
      final responder = await DeviceIdentity.generate(name: 'mac', platform: 'macos');
      final impostor = await DeviceIdentity.generate(name: 'evil', platform: 'macos');
      final eI = await newEphemeralKeyPair(), eR = await newEphemeralKeyPair();
      final f1 = buildFrame1(ephemeralPublic: await publicKeyOf(eI), staticPublic: initiator.publicKey, deviceId: initiator.device.id);
      final f2 = buildFrame2(await publicKeyOf(eR));

      final i = await deriveInitiatorKeys(ephemeral: eI, static: initiator.keyPair, responderStatic: responder.publicKey, responderEphemeral: await publicKeyOf(eR), frame1: f1, frame2: f2);
      final r = await deriveResponderKeys(ephemeral: eR, static: responder.keyPair, initiatorStatic: initiator.publicKey, initiatorEphemeral: await publicKeyOf(eI), frame1: f1, frame2: f2);
      final wrong = await deriveResponderKeys(ephemeral: eR, static: impostor.keyPair, initiatorStatic: initiator.publicKey, initiatorEphemeral: await publicKeyOf(eI), frame1: f1, frame2: f2);

      expect(await i.send.extractBytes(), await r.receive.extractBytes());
      expect(await i.receive.extractBytes(), await r.send.extractBytes());
      expect(await wrong.receive.extractBytes(), isNot(await i.send.extractBytes()));

      final sealed = await FrameCipher(i.send).seal([1, 2, 3]);
      expect(await FrameCipher(r.receive).open(sealed), [1, 2, 3]);
      await expectLater(FrameCipher(wrong.receive).open(sealed), throwsA(isA<ProtocolException>()));
    });
  });

  group('sessions over loopback', () {
    late DeviceIdentity mac, phone;
    late _Policy policy;
    late ServerSocket server;
    late StreamController<SyncSession> accepted;

    setUp(() async {
      mac = await DeviceIdentity.generate(name: 'Mac', platform: 'macos');
      phone = await DeviceIdentity.generate(name: 'Phone', platform: 'android');
      policy = _Policy();
      accepted = StreamController<SyncSession>();
      server = await ServerSocket.bind(InternetAddress.loopbackIPv4, 0);
      server.listen((socket) {
        SyncSession.accept(socket, identity: mac, policy: policy).then(accepted.add, onError: accepted.addError);
      });
    });

    tearDown(() async {
      await server.close();
      // Not awaited: close() only completes once a listener sees "done", and
      // the refusal tests never listen.
      unawaited(accepted.close());
    });

    Future<SyncSession> connect({Uint8List? token, DeviceIdentity? as}) => SyncSession.connect(
          host: '127.0.0.1',
          port: server.port,
          identity: as ?? phone,
          peerStaticKey: mac.publicKey,
          expectedPeerId: mac.device.id,
          pairingToken: token,
        );

    test('pair, exchange clips both ways, reconnect as paired', () async {
      policy.token = _randomBytes(16);
      final phoneSide = await connect(token: policy.token);
      final macSide = await accepted.stream.first;
      expect(phoneSide.pairedNow, isTrue);
      expect(policy.paired.keys, [phone.device.id]);
      expect(policy.pairingOpen, isFalse, reason: 'token is single-use');

      final toMac = macSide.clips.first;
      await phoneSide.sendClip(ClipMessage.text('from phone', origin: phone.device.id));
      expect((await toMac).text, 'from phone');

      final image = _randomBytes(2 * 1024 * 1024);
      final toPhone = phoneSide.clips.first;
      await macSide.sendClip(ClipMessage.png(image, origin: mac.device.id));
      expect((await toPhone).body, image);

      await phoneSide.close();
      await macSide.done;

      // Second connection: no token, accepted because paired.
      final again = await connect();
      expect(again.pairedNow, isFalse);
      expect(again.peer.id, mac.device.id);
      await again.close();
    });

    test('unpaired device without a pairing window is refused', () async {
      await expectLater(connect(), throwsA(isA<ProtocolException>()));
    });

    test('wrong pairing token is refused and not stored', () async {
      policy.token = _randomBytes(16);
      await expectLater(connect(token: _randomBytes(16)), throwsA(isA<ProtocolException>()));
      expect(policy.paired, isEmpty);
    });

    test('a device presenting a paired id with a different key is refused', () async {
      policy.token = _randomBytes(16);
      final first = await connect(token: policy.token);
      await first.close();
      final thief = await DeviceIdentity.restore(phone.device, _randomBytes(32));
      await expectLater(connect(as: thief), throwsA(isA<ProtocolException>()));
    });

    test('listening ports travel both ways; peers that omit them read as null', () async {
      await server.close();
      // A responder that announces its own listening port (a phone).
      server = await ServerSocket.bind(InternetAddress.loopbackIPv4, 0);
      server.listen((socket) {
        SyncSession.accept(socket, identity: mac, policy: policy, listenPort: 47474)
            .then(accepted.add, onError: accepted.addError);
      });
      policy.token = _randomBytes(16);
      final phoneSide = await SyncSession.connect(
        host: '127.0.0.1',
        port: server.port,
        identity: phone,
        peerStaticKey: mac.publicKey,
        pairingToken: policy.token,
        listenPort: 51000,
      );
      final incoming = StreamQueue(accepted.stream);
      final macSide = await incoming.next;
      expect(phoneSide.peerListenPort, 47474);
      expect(macSide.peerListenPort, 51000);
      expect(macSide.remoteAddress, '127.0.0.1');
      await phoneSide.close();

      // Reconnect without announcing a port (like the Mac app does).
      final quiet = await connect();
      final quietMacSide = await incoming.next;
      expect(quietMacSide.peerListenPort, isNull);
      await quiet.close();
    });

    test('duplicate clip ids are delivered once', () async {
      policy.token = _randomBytes(16);
      final phoneSide = await connect(token: policy.token);
      final macSide = await accepted.stream.first;
      final received = <String>[];
      macSide.clips.listen((c) => received.add(c.text!));
      final clip = ClipMessage.text('once', origin: phone.device.id);
      await phoneSide.sendClip(clip);
      await phoneSide.sendClip(clip);
      await phoneSide.sendClip(ClipMessage.text('twice', origin: phone.device.id));
      await Future<void>.delayed(const Duration(milliseconds: 200));
      expect(received, ['once', 'twice']);
      await phoneSide.close();
    });
  });
}
