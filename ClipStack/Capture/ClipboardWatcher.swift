import AppKit
import Foundation

/// Polls NSPasteboard.general.changeCount (~0.3 s) — macOS has no public
/// pasteboard-change notification. Honors nspasteboard.org privacy flags.
final class ClipboardWatcher {
    /// PasteService marks its own pasteboard writes with this type so we
    /// don't re-ingest our own pastes.
    static let selfWriteType = NSPasteboard.PasteboardType("com.zamansheikh.clipstack.self-write")

    private static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    private let pasteboard = NSPasteboard.general
    private let ingest: IngestPipeline
    private var timer: Timer?
    private var lastChangeCount: Int

    /// "Pause capture" toggle from the menu bar.
    var isPaused = false

    init(ingest: IngestPipeline) {
        self.ingest = ingest
        self.lastChangeCount = pasteboard.changeCount
    }

    func start() {
        stop()
        let timer = Timer(timeInterval: 0.3, repeats: true) { [weak self] _ in
            self?.tick()
        }
        // .common so polling keeps running while menus/tracking loops are open.
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func tick() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        guard !isPaused else { return }

        let types = pasteboard.types ?? []
        // Never store concealed/transient content (password managers), and
        // skip our own paste writes — PasteService bumps the row itself.
        if types.contains(Self.concealedType)
            || types.contains(Self.transientType)
            || types.contains(Self.autoGeneratedType)
            || types.contains(Self.selfWriteType)
        {
            return
        }

        ingest.capture(from: pasteboard)
    }
}
